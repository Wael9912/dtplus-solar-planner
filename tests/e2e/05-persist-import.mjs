// Scenario 5: persistence across reload, duplicate/delete (+undo), search/filter, import of previously exported JSON.
import fs from 'node:fs'; import path from 'node:path'
import { launch, DESKTOP, DL, shot, checkPage, reportErrors, gotoApp, goStep, loadSamples, clearStorage, issue, pass, summary, nav, openCard, projectCards } from './lib.mjs'
const files = JSON.parse(fs.readFileSync(path.join(DL, 'files.json'), 'utf8'))
const { browser, page, errors } = await launch(DESKTOP)
await gotoApp(page); await clearStorage(page); await page.reload({ waitUntil: 'networkidle' }); await loadSamples(page)
await openCard(page, 0); await page.getByLabel('Project name').fill('Renamed after reload')
await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(200)
const view = await page.locator('body').innerText()
if (!/Renamed after reload/.test(view)) issue('persist: renamed project not shown after reload')
else pass(`persist: reload restores view (${/Projects/.test(view.slice(0, 200)) ? 'projects' : 'wizard'})`)
// browser back goes to the project list instead of leaving the app
await page.goBack(); await page.waitForTimeout(200)
if (!(await projectCards(page).count())) { await nav(page, 'projects') } else pass('history: back button returns to the projects list')
const cards = projectCards(page)
if ((await cards.count()) !== 4) issue(`persist: expected 4 cards after reload, got ${await cards.count()}`); else pass('persist: 4 cards after reload')
// duplicate + delete (+ undo)
await cards.nth(0).getByTestId('project-menu').click(); await page.getByTestId('project-duplicate').click(); await page.waitForTimeout(150)
if ((await cards.count()) !== 5 || !/\(copy\)/.test(await page.locator('body').innerText())) issue('duplicate failed')
await cards.nth(0).getByTestId('project-menu').click(); await page.getByTestId('project-delete').click(); await page.getByRole('button', { name: 'Yes, delete' }).click(); await page.waitForTimeout(150)
if ((await cards.count()) !== 4) issue('delete failed'); else pass('duplicate + delete')
await page.getByRole('button', { name: 'Undo' }).last().click(); await page.waitForTimeout(150)
if ((await cards.count()) !== 5) issue('undo delete failed'); else pass('undo delete')
await cards.nth(0).getByTestId('project-menu').click(); await page.getByTestId('project-delete').click(); await page.getByRole('button', { name: 'Yes, delete' }).click(); await page.waitForTimeout(150)
// search + empty search message + status filter
await page.getByPlaceholder('Search projects…').fill('khartoum'); await page.waitForTimeout(300)
if ((await cards.count()) !== 1) issue(`search filter failed: ${JSON.stringify(await cards.locator('h2').allInnerTexts())}`)
await page.getByPlaceholder('Search projects…').fill('zzzz'); await page.waitForTimeout(200)
if (!/No projects match “zzzz”/.test(await page.locator('main').innerText())) issue('search: wrong empty-search message'); else pass('search: empty-search message')
await page.getByRole('button', { name: 'Clear filters' }).click()
await page.getByTestId('filter-approved').click(); await page.waitForTimeout(150)
if ((await cards.count()) !== 1) issue(`status filter: expected 1 approved, got ${await cards.count()}`); else pass('status filter')
await page.getByRole('button', { name: /^All/ }).click()
// import
await page.getByTestId('import-file').setInputFiles(files.json); await page.waitForTimeout(400)
if ((await cards.count()) !== 5) issue(`import: expected 5 cards, got ${await cards.count()}`)
const body = await page.locator('body').innerText()
if (!/QA Villa Hybrid/.test(body)) issue('import: imported project name missing')
if (!/SDG/.test(body)) issue('import: imported SDG total not shown'); else pass('import: QA Villa Hybrid card with SDG total')
await shot(page, '05-imported'); await checkPage(page, 'imported list'); reportErrors(errors, 'import')
// import twice -> id collision handled
await page.getByTestId('import-file').setInputFiles(files.json); await page.waitForTimeout(300)
if ((await cards.count()) !== 6) issue('import twice: expected 6 cards'); else pass('import twice handled (new id)')
let qi = -1; for (let i = 0; i < 6; i++) if (/QA Villa Hybrid/.test(await cards.nth(i).innerText())) { qi = i; break }
await openCard(page, qi)
for (let s = 0; s < 7; s++) { await goStep(page, s); await checkPage(page, `imported step ${s + 1}`); reportErrors(errors, `imported step ${s + 1}`) }
await goStep(page, 5); await page.getByTestId('view-cost').click(); await shot(page, '05-imported-bom')
const customNames = await page.locator('[data-line-id] input:not([inputmode])').evaluateAll((es) => es.map((e) => e.value)); if (!customNames.includes('Scaffolding')) issue(`import: custom BOM line lost (${customNames})`)
await page.getByTestId('bom-menu').click(); const removedTxt = await page.getByTestId('bom-show-removed').innerText().catch(() => '')
if (!/1/.test(removedTxt)) issue('import: excluded line lost'); else pass('import: overrides, exclusions, custom line intact')
await page.keyboard.press('Escape')
// bad JSON import → error toast, nothing imported
const bad = path.join(DL, 'bad.json'); fs.writeFileSync(bad, '{"nope":1}')
await nav(page, 'projects'); await page.getByTestId('import-file').setInputFiles(bad); await page.waitForTimeout(300)
if ((await cards.count()) !== 6) issue('bad import changed project count'); else pass('bad JSON rejected')
if (!/isn’t a project/.test(await page.locator('body').innerText())) issue('bad import: no error message shown')
reportErrors(errors, 'bad import')
await browser.close(); summary('05-persist-import')
